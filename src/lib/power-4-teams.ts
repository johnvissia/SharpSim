// Maps conference ID prefix (e.g., "b1g") to full name.
const conferenceIdToName: Record<string, string> = {
    'b1g': 'Big 10',
    'sec': 'SEC',
    'b12': 'Big 12',
    'acc': 'ACC',
};

// Create a map from espn_name to conference name
export const power4ConferenceMap = new Map<string, string>();
POWER_4_TEAMS.forEach(team => {
    const conferencePrefix = team.id.split('_')[0];
    const conferenceName = conferenceIdToName[conferencePrefix];
    if (conferenceName) {
        power4ConferenceMap.set(team.espn_name, conferenceName);
    }
});

// Create a set of all espn_names for quick lookups for filtering games
export const power4TeamNames = new Set(POWER_4_TEAMS.map(team => team.espn_name));
